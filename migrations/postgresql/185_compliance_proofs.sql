-- F-03 — counterfactual compliance proofs.
--
-- Design: docs/Future/Done/AI-ERA-ROADMAP.md §F-03. HxArbiter can already answer
-- *"if this draft had been live, what would have decided differently"* — that
-- is `hxarbiter/nlp/whatif.py`, added in ARB-F. What it produces is a report
-- for a person about to press a button: capped at 2,000 rows, over 30 days,
-- kept on the draft, and never re-derivable.
--
-- An auditor asks a different question. Not "what might change" but *"prove to
-- me what WOULD have happened, across the entire caseload, and let me
-- re-derive it myself"*. That needs three things the report is not:
--
--   * the WHOLE cohort, not a sample — "0 of 12,844" is the claim, and a
--     sample cannot make it;
--   * a fixed, content-addressed document, so two people arguing about a
--     number are arguing about the same document;
--   * an append-only chain, so a proof cannot be quietly removed or
--     back-dated once its result is inconvenient.
--
-- NOTHING HERE CHANGES BEHAVIOUR ON UPGRADE. One new table. Generating a proof
-- is read-only over the decision log; it evaluates and writes one row.

CREATE TABLE IF NOT EXISTS compliance_proofs (
    id              UUID         PRIMARY KEY,

    -- NULL means a PLATFORM-scope proof, which is superadmin-only and
    -- aggregate-only: a cohort definition can leak which cases exist, so a
    -- cross-tenant proof reports distributions and never the divergent list.
    tenant_id       UUID         NULL REFERENCES tenants(id) ON DELETE CASCADE,

    -- What was replayed. A policy version is the only subject today; the column
    -- exists because F-04 replays a PROCESS version through the same machinery,
    -- and a proof that cannot say what it was about is not a proof.
    subject_kind    VARCHAR(32)  NOT NULL DEFAULT 'policy_version',
    policy_id       UUID         NULL,
    policy_version  INTEGER      NULL,
    namespace       VARCHAR(64)  NOT NULL,

    -- complete | refused. A REFUSED proof is stored, not discarded: "we could
    -- not prove this, and here is exactly why" is an answer an auditor is
    -- entitled to keep, and silently returning nothing invites the question
    -- being asked again until it accidentally succeeds.
    status          VARCHAR(20)  NOT NULL DEFAULT 'complete',
    refusal_reason  TEXT         NULL,

    -- The cohort as a definition, not as a list: window, filters, and the
    -- counts it resolved to. An auditor re-running the proof needs the
    -- definition; the ids are covered by `inputs_sha256` below.
    cohort          JSONB        NOT NULL DEFAULT '{}'::jsonb,

    -- The two commitments that make this re-derivable. `inputs_sha256` covers
    -- the ordered decision ids AND the attributes each was replayed against, so
    -- a later edit to any of them is detectable; `rules_sha256` covers the
    -- exact rule set. Same inputs plus same rules must give the same result, on
    -- the auditor's own instance.
    inputs_sha256   CHAR(64)     NOT NULL,
    rules_sha256    CHAR(64)     NOT NULL,

    result          JSONB        NOT NULL DEFAULT '{}'::jsonb,
    -- The divergent decisions, in full. Filtered per VIEWER at read time rather
    -- than at write time: the count is the proof's finding and must not depend
    -- on who is looking, while the list is case data and must.
    divergent       JSONB        NOT NULL DEFAULT '[]'::jsonb,
    aggregate_only  BOOLEAN      NOT NULL DEFAULT FALSE,

    -- ── the chain ───────────────────────────────────────────────────────────
    --
    -- `content_sha256` is the document's ADDRESS: the hash of everything above.
    -- `prev_hash` links it to the proof before it, so removing or back-dating
    -- one breaks every proof after it. Same construction as the audit, arbiter
    -- and ledger chains — a fourth invention would be a fourth thing to get
    -- wrong.
    --
    -- Per proof rather than batched, unlike the other three: proofs are
    -- generated by hand, minutes or months apart, and a time-windowed batch
    -- over an empty period would be pure ceremony.
    prev_hash       CHAR(64)     NOT NULL,
    content_sha256  CHAR(64)     NOT NULL,
    sequence        BIGINT       NOT NULL,

    generated_by    UUID         NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT ux_proof_sequence UNIQUE (sequence)
);

CREATE INDEX IF NOT EXISTS ix_proof_tenant  ON compliance_proofs (tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_proof_policy  ON compliance_proofs (policy_id, policy_version);
CREATE INDEX IF NOT EXISTS ix_proof_content ON compliance_proofs (content_sha256);
